"""Shared policy and file lifecycle for WireGuard and networkd exports."""

from __future__ import annotations

import ipaddress
import logging
import re
import stat
from abc import ABC, abstractmethod
from pathlib import Path

from ..domains import plan_dns_domains, report_domains
from ..keys import is_wireguard_key
from ..model import (ProfileTarget, RouteOptions, RoutePolicy, WireGuardTunnel, WriteOptions,
                     dns_suffix, interface_name, policy_search_domains)
from ._files import Artifact, existing_file, locked_directory, publish, read_profile


LOG = logging.getLogger(__name__)
HEADER = '# Generated by unwarp'


def words(values):
    return [item for value in values for item in value.replace(',', ' ').split()]


def check_address_family(addresses, options):
    if not options.ipv4_only and not any(ipaddress.ip_interface(a).version == 6 for a in addresses):
        raise ValueError('--dual-stack requires a profile with an IPv6 address')


def allowed_networks(policy, options, previous):
    """Minimize each family after mandatory exclusions; keep unselected IPv6 on refresh."""
    networks = list(ipaddress.collapse_addresses(policy.included_routes(4)))
    if options.ipv4_only:
        existing = (ipaddress.ip_network(value, strict=False) for value in previous)
        networks.extend(net for net in existing if net.version == 6)
    else:
        networks.extend(ipaddress.collapse_addresses(policy.included_routes(6)))
    return list(map(str, networks))


def validate_tunnel(tunnel, options):
    for key in (tunnel.private_key, tunnel.peer_public_key):
        if not is_wireguard_key(key):
            raise ValueError('expected a base64-encoded 32-byte WireGuard key')
    endpoint = re.fullmatch(r'(?:[a-zA-Z0-9_.-]+|\[[a-fA-F0-9:.]+\]):([0-9]{1,5})', tunnel.endpoint)
    if not endpoint or not 1 <= int(endpoint[1]) <= 65535:
        raise ValueError('expected a WireGuard endpoint with a host and port')
    if not options.ipv4_only and tunnel.address6 is None:
        raise ValueError('dual-stack output requires an IPv6 tunnel address')


class FileBackend(ABC):
    directory: Path
    extensions: tuple[str, ...]
    domain_file: str
    prefix = ''
    supports_qr = False
    routing_domains = False

    def reserved_interfaces(self, directory):
        names = set()
        for ext in self.extensions:
            names.update(p.stem.removeprefix(self.prefix)
                         for p in (directory or self.directory).glob(f'{self.prefix}*.{ext}'))
        return names

    def validate_name(self, name):
        interface_name(name)

    @abstractmethod
    def render(self, name: str, tunnel: WireGuardTunnel, routes: RouteOptions) -> dict[str, str]:
        """Render the base files using the supplied interface and peer."""

    @abstractmethod
    def domains(self, text: str) -> list[str]:
        """Read DNS search domains from the file carrying link settings."""

    @abstractmethod
    def set_policy(self, files, policy, options, domains) -> dict[str, str]:
        """Patch the managed fields in the single-peer profile."""

    def artifact(self, ext, text, directory):
        return Artifact(text.encode('utf-8'))

    def check_output(self, output, directory):
        if output.reload:
            raise ValueError('this backend exports a WireGuard configuration file; omit --reload')

    def reload(self, interface):
        raise NotImplementedError

    def sidecars(self, paths):
        return ()

    def finish_export(self, paths, files, output):
        pass

    def write_profile(self, target: ProfileTarget, tunnel: WireGuardTunnel,
                      routes: RouteOptions, output: WriteOptions) -> None:
        if tunnel.policy is None and routes.sync_domains:
            raise ValueError('--sync-domains requires a split-tunnel policy')
        validate_tunnel(tunnel, routes)
        self._update(target, tunnel.policy or RoutePolicy('include'), routes, output, tunnel)

    def apply_routes(self, target: ProfileTarget | str, policy: RoutePolicy, routes: RouteOptions) -> None:
        output = WriteOptions(directory=routes.directory, overwrite=True, reload=routes.reload)
        self._update(target, policy, routes, output, tunnel=None)

    def _update(self, target, policy, routes, output, tunnel):
        if policy.mode != 'include':
            raise ValueError('exporting static routes requires an Include-mode policy')
        name = target.interface if isinstance(target, ProfileTarget) else target
        self.validate_name(name)
        directory = output.directory or self.directory
        self.check_output(output, directory)
        paths = {ext: directory / f'{self.prefix}{name}.{ext}' for ext in self.extensions}
        header = HEADER
        if isinstance(target, ProfileTarget) and target.uuid:
            header += ' ' + target.uuid
        with locked_directory(directory):
            old = self._read_files(paths, header, refresh=tunnel is None)
            files = old
            if not old or output.overwrite:
                if tunnel is not None:
                    files = {ext: f'{header}\n{text}' for ext, text in self.render(name, tunnel, routes).items()}
                current = self.domains(old[self.domain_file]) if self.domain_file in old else []
                wanted = [*routes.extra_domains, *policy_search_domains(policy.domains)]
                merged, outside, rewrites = plan_dns_domains(current, wanted, routes.sync_domains)
                files = self.set_policy(files, policy, routes, [self._export_domain(d) for d in merged])
                self._save(directory, paths, old, files, output.dry_run)
                report_domains('DNS search domains', outside, routes.sync_domains, output.dry_run, rewrites)
            elif old.keys() != paths.keys():
                raise ValueError(f'incomplete profile for {name}; regenerate with --overwrite')
            else:
                LOG.info('profile already exists in %s; use --overwrite to regenerate', directory)
            if not output.dry_run:
                self.finish_export(paths, files, output)
        if output.reload and not output.dry_run:
            self.reload(name)

    @staticmethod
    def _read_files(paths, header, refresh):
        files = {}
        for ext, path in paths.items():
            text = read_profile(path)
            if text is None:
                if refresh:
                    raise ValueError(f'missing profile file {path}')
                continue
            marker = next((line.strip() for line in text.splitlines()
                           if line.strip() == HEADER or line.strip().startswith(HEADER + ' ')), None)
            if marker and header != HEADER and marker != HEADER and marker != header:
                raise ValueError(f'a different unwarp profile already uses {path}')
            if refresh and marker is None:
                raise ValueError('routes --apply requires a profile generated by unwarp')
            files[ext] = text
        return files

    def _save(self, directory, paths, old, files, dry_run):
        changes = {}
        for ext, text in files.items():
            path = paths[ext]
            artifact = self.artifact(ext, text, directory)
            if text == old.get(ext):
                current = path.lstat()
                if (stat.S_IMODE(current.st_mode) == artifact.mode
                        and (artifact.group is None or current.st_gid == artifact.group)):
                    continue
            changes[path] = artifact
        if old and files != old:
            for path in self.sidecars(paths):
                if existing_file(path):
                    changes[path] = None
        if dry_run:
            LOG.info('would write %s', ', '.join(str(p) for p in changes) or 'no changes')
            return
        publish(directory, changes)
        for path, artifact in changes.items():
            if artifact is None:
                LOG.warning('Removed outdated QR image %s', path)
            else:
                LOG.info('saved %s', path)

    def _export_domain(self, value):
        if value.startswith('~'):
            if not self.routing_domains:
                raise ValueError('routing-only DNS domains (~domain) require NetworkManager or systemd-networkd')
            return '~.' if value == '~.' else '~' + dns_suffix(value[1:])
        return dns_suffix(value)
